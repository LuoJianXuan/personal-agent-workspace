from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
schema=json.loads((ROOT/'schemas/jsonschema/contracts.json').read_text(encoding='utf-8'))
def field(s,lang):
 if '$ref' in s:return s['$ref'].split('/')[-1]
 if 'oneOf' in s:return {'go':'json.RawMessage','py':'Any','ts':' | '.join(field(x,'ts') for x in s['oneOf'])}[lang]
 if s.get('type')=='array':
  t=field(s['items'],lang);return {'go':'[]'+t,'py':'list['+t+']','ts':'Array<'+t+'>'}[lang]
 if 'enum' in s and lang in ('py','ts'):
  vals=[json.dumps(x) for x in s['enum']];return 'Literal['+', '.join(vals)+']' if lang=='py' else ' | '.join(vals)
 return {'string':{'go':'string','py':'str','ts':'string'},'integer':{'go':'int64','py':'int','ts':'number'},'number':{'go':'float64','py':'float','ts':'number'},'boolean':{'go':'bool','py':'bool','ts':'boolean'},'object':{'go':'json.RawMessage','py':'dict[str, Any]','ts':'Record<string, unknown>'}}[s['type']][lang]
out={'go':'// Generated by scripts/generate-contracts.py. Do not edit.\npackage contracts\nimport "encoding/json"\n','py':'# Generated. Validate with shared JSON Schema before using DTOs.\nfrom __future__ import annotations\nfrom typing import Any, Literal, TypedDict, NotRequired\n','ts':'// Generated. Validate external data with shared JSON Schema.\n'}
for name,s in schema['$defs'].items():
 out['go']+='type '+name+' struct {\n';out['py']+='class '+name+'(TypedDict):\n';out['ts']+='export interface '+name+' {\n'
 for k,v in s['properties'].items():
  optional=k not in s['required'];g=field(v,'go');py=field(v,'py')
  out['go']+='  '+''.join(x.title() for x in k.split('_'))+' '+('*'+g if optional else g)+' `json:"'+k+(',omitempty' if optional else '')+'"`\n'
  out['py']+='    '+k+': '+('NotRequired['+py+']' if optional else py)+'\n'
  out['ts']+='  '+k+('?' if optional else '')+': '+field(v,'ts')+';\n'
 out['go']+='}\n';out['py']+='\n';out['ts']+='}\n'
for lang,path in [('go','services/backend/internal/contracts/models.go'),('py','services/runtime/contracts/models.py'),('ts','apps/web/src/contracts/models.ts')]:
 (ROOT/path).write_text(out[lang],encoding='utf-8')
for path in ['services/backend/internal/contracts/schema.json','services/runtime/contracts/schema.json','apps/web/src/contracts/schema.json']:
 (ROOT/path).write_text(json.dumps(schema,ensure_ascii=False,indent=2),encoding='utf-8')

for path in ["services/backend/internal/control/builtin-tools.json","services/runtime/contracts/builtin-tools.json"]:
 (ROOT/path).write_text((ROOT/"schemas/builtin-tools.json").read_text(encoding="utf-8"),encoding="utf-8")
